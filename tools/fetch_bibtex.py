#!/usr/bin/env python
"""Regenerate ``references.bib`` from ADS using each entry's ``bibcode``/``arxiv``.

    export ADS_API_TOKEN=...   # https://ui.adsabs.harvard.edu/user/settings/token
    python tools/fetch_bibtex.py > src/barycon/data/references.bib

Entries are re-keyed with the BaryCon id so that ``Collection.bibtex()`` finds them.
"""
import os
import re
import sys

import requests

import barycon as bc

TOKEN = os.environ.get("ADS_API_TOKEN")
if not TOKEN:
    sys.exit("set ADS_API_TOKEN")
H = {"Authorization": f"Bearer {TOKEN}"}
API = "https://api.adsabs.harvard.edu/v1"


def bibcode_for(meta):
    if meta.get("bibcode"):
        return meta["bibcode"]
    if meta.get("arxiv"):
        r = requests.get(f"{API}/search/query", headers=H,
                         params={"q": f"identifier:arXiv:{meta['arxiv']}", "fl": "bibcode"}, timeout=30)
        docs = r.json()["response"]["docs"]
        return docs[0]["bibcode"] if docs else None
    return None


seen = {}
for e in bc.load(include_pending=True):
    key = e.id.split("_")[0]
    if key not in seen:
        seen[key] = bibcode_for(e.meta)
codes = {k: v for k, v in seen.items() if v}
r = requests.post(f"{API}/export/bibtex", headers=H, json={"bibcode": list(codes.values())}, timeout=60)
bib = r.json()["export"]
for key, code in codes.items():
    bib = re.sub(r"@(\w+)\{" + re.escape(code) + ",", "@\\1{" + key + ",", bib)
print("% generated by tools/fetch_bibtex.py from NASA ADS\n" + bib)
missing = sorted(set(seen) - set(codes))
if missing:
    print(f"% WARNING: no ADS record for {missing}", file=sys.stderr)
